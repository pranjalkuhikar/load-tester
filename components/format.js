export const num = (n, d = 0) => (n == null || !isFinite(n) ? "–" : Number(n).toLocaleString("en-US", { maximumFractionDigits: d }));
export const ms = (n) => (n == null || !isFinite(n) ? "–" : n >= 1000 ? (n / 1000).toFixed(2) + " s" : n >= 100 ? n.toFixed(0) + " ms" : n >= 10 ? n.toFixed(1) + " ms" : n.toFixed(2) + " ms");
export const pct = (n) => (n == null || !isFinite(n) ? "–" : n === 0 ? "0%" : n < 0.01 ? "<0.01%" : n < 1 ? n.toFixed(2) + "%" : n.toFixed(1) + "%");
export const bytes = (n) => (n < 1024 ? n.toFixed(0) + " B" : n < 1048576 ? (n / 1024).toFixed(1) + " KB" : n < 1073741824 ? (n / 1048576).toFixed(1) + " MB" : (n / 1073741824).toFixed(2) + " GB");
export const dur = (s) => {
  if (s == null || !isFinite(s)) return "–";
  s = Math.round(s);
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), x = s % 60;
  return h ? `${h}h ${m}m` : m ? `${m}m ${String(x).padStart(2, "0")}s` : `${x}s`;
};
export const when = (t) => new Date(t).toLocaleString(undefined, { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" });
export const short = (n) => (n >= 1e6 ? n / 1e6 + "M" : n >= 1e3 ? n / 1e3 + "k" : String(n));

// Markdown report for sharing a result (Copy report)
export function buildReport(v, cfg) {
  const t = v.totals, an = v.analysis, lines = [];
  const title = (cfg && cfg.name) || (cfg && cfg.base) || "Load test";
  lines.push(`# LoadLab report: ${title}`, "");
  if (an) lines.push(`**Verdict: ${an.verdict.status}**, ${an.verdict.headline}`, an.verdict.reason ? `\n_Why:_ ${an.verdict.reason}` : "", "");
  if (cfg) lines.push(`- **Target:** ${cfg.base}`, `- **Type:** ${cfg.mode}${cfg.mode === "steps" ? ` (${cfg.steps.levels.join(", ")} users, ${cfg.steps.secondsPerStep}s each)` : cfg.mode === "duration" ? ` (${cfg.durationSec}s, ${cfg.concurrency} users)` : ` (${num(cfg.total)} requests, ${cfg.concurrency} users)`}`, `- **SLO:** p95 under ${cfg.slo.p95Ms} ms, errors under ${cfg.slo.errorPct}%`);
  if (v.startedAt) lines.push(`- **Date:** ${new Date(v.startedAt).toLocaleString()}`);
  lines.push(`- **Duration:** ${dur(v.elapsed)}`, "", "## Summary", "", "| Metric | Value |", "|---|---|",
    `| Requests | ${num(t.done)} |`, `| Requests/sec | ${num(t.avgRps)} (peak ${num(v.peakRps)}) |`,
    `| Latency p50 / p95 / p99 | ${ms(t.p50)} / ${ms(t.p95)} / ${ms(t.p99)} |`, `| Avg / min / max | ${ms(t.avg)} / ${ms(t.min)} / ${ms(t.max)} |`,
    `| Errors | ${pct(t.errorPct)} (${num(t.errors)}) |`, `| Data received | ${bytes(t.bytes)} |`, "");
  if (v.phases && v.phases.length > 1) {
    lines.push("## Step results", "", "| Users | Req/s | p50 | p95 | p99 | Errors |", "|---:|---:|---:|---:|---:|---:|");
    for (const p of v.phases) lines.push(`| ${p.concurrency} | ${num(p.rps)} | ${ms(p.p50)} | ${ms(p.p95)} | ${ms(p.p99)} | ${pct(p.errorPct)} |`);
    lines.push("");
  }
  lines.push("## Per endpoint", "", "| Endpoint | Requests | Req/s | p50 | p95 | p99 | Errors |", "|---|---:|---:|---:|---:|---:|---:|");
  for (const e of v.eps || []) lines.push(`| ${e.name} | ${num(e.done)} | ${num(e.rps, 1)} | ${ms(e.p50)} | ${ms(e.p95)} | ${ms(e.p99)} | ${pct(e.errorPct)} |`);
  if (an && an.insights.length) {
    lines.push("", "## Findings", "");
    for (const i of an.insights) lines.push(`- **${i.title}** (${i.level}): ${i.detail}${i.fix ? ` _Fix:_ ${i.fix}` : ""}`);
  }
  lines.push("", "_Generated by LoadLab_");
  return lines.filter((l) => l !== undefined).join("\n");
}
